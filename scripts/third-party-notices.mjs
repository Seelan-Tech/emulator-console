// Writes THIRD_PARTY_NOTICES.md: every production dependency with its version, license and home page, read from
// the installed packages (run `npm ci` first). Regenerate it when dependencies change: `npm run notices`.
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const lock = JSON.parse(readFileSync(join(root, "package-lock.json"), "utf8"));
const rows = [];
for (const [path, info] of Object.entries(lock.packages)) {
  if (!path || info.dev || info.devOptional) continue;
  const file = join(root, path, "package.json");
  if (!existsSync(file)) continue; // optional dependency for another platform
  const p = JSON.parse(readFileSync(file, "utf8"));
  const license =
    typeof p.license === "string"
      ? p.license
      : (p.license?.type ?? p.licenses?.map?.((l) => l.type).join(" OR ") ?? "UNKNOWN");
  const repo = (typeof p.repository === "string" ? p.repository : p.repository?.url) ?? p.homepage ?? "";
  rows.push({
    name: p.name,
    version: p.version,
    license,
    url: repo
      .replace(/^git\+/, "")
      .replace(/\.git$/, "")
      .replace(/^git:\/\//, "https://")
      .replace(/^github:/, "https://github.com/"),
  });
}
rows.sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));

const counts = new Map();
for (const r of rows) counts.set(r.license, (counts.get(r.license) ?? 0) + 1);

const text = `# Third-party notices

Emulator Console is released under the [MIT license](LICENSE). It is built on the open-source packages listed below,
each under its own license. This file is generated by \`npm run notices\`; do not edit it by hand.

The AWS Emulator is a separate project. It is not part of this repository and is downloaded from AWS when the
emulator image is built.

## Summary

${[...counts]
  .sort((a, b) => b[1] - a[1])
  .map(([l, n]) => `- ${l}: ${n}`)
  .join("\n")}

A few notes: \`@img/sharp-libvips-*\` (LGPL-3.0-or-later) is an optional image-processing dependency of Next.js for
the build machine and is removed from the runtime image; \`lightningcss\` (MPL-2.0) and \`caniuse-lite\` (CC-BY-4.0, browser
data) are build-time tools.

## Packages

| Package | Version | License | Source |
| --- | --- | --- | --- |
${rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.url ? `<${r.url}>` : ""} |`).join("\n")}
`;
writeFileSync(join(root, "THIRD_PARTY_NOTICES.md"), text);
console.log(`wrote THIRD_PARTY_NOTICES.md (${rows.length} packages)`);
